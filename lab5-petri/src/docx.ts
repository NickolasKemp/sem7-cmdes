const arcText = (a: Arc): string => `${a.place.name}${a.shown ? ` (×${a.shown})` : a.weight > 1 ? ` (×${a.weight})` : ''}`;

const delayText = (t: Transition): string => (t.delay.mean === 0 && t.delay.label.startsWith('const') ? '0' : label(t.delay.label));

const ruleText = (t: Transition): string =>
  [t.priority ? `pr = ${t.priority}` : '', t.probability !== 1 ? `p = ${label(String(+t.probability.toFixed(3)))}` : ''].filter(Boolean).join('; ') || '—';

/** Таблиця переходів: події моделі, їхні передумови й післяумови, затримка та спосіб розв’язання конфлікту. */
const transitionsTable = (net: Net, keep: (t: Transition) => boolean = () => true): Block[] =>
  table(
    ['Перехід (подія)', 'Вхідні позиції', 'Вихідні позиції', 'Затримка', 'pr, p'],
    net.transitions
      .filter(keep)
      .map((t) => [
        t.name,
        [...t.inputs.map(arcText), ...t.info.map((a) => `${arcText(a)} — інф.`)].join('; '),
        t.outputs.filter((a) => !a.place.name.startsWith('генератор')).map(arcText).join('; ') || '—',
        delayText(t),
        ruleText(t),
      ]),
    [1.5, 2.2, 2, 1, 0.8],
  );

const initialMarking = (net: Net): string =>
  net.places
    .filter((p) => p.initial > 0 && !p.name.startsWith('генератор'))
    .map((p) => `«${p.name}» — ${p.layout?.shown ?? p.initial}`)
    .join(', ');

const est = (e: Estimate, digits = 2, scale = 1): string => pm(e, digits, scale);
const share = (e: Estimate): string => `${num(e.mean * 100, 1)} ± ${num(e.halfWidth * 100, 1)} %`;

